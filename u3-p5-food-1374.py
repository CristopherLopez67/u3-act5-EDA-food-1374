import pandas as pd
import matplotlib.pyplot as plt
## Mario Yañez NC 1110
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV, comida India 1110 ---")
print(df_food_india)
print("\n--- Mostrar nombre comida + ingredientes, comida India 1110 ---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- Tiempo de cocinado mostrar 10 registros con head 1110 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (X) Tiempo de cocinado (y)----")
print("\n--- Grafica comida (x) texto a 20 grados ---")
nombre_y_hora.plot.bar(x='name', y='cook_time', rot=30)
plt.title('comida tipica de infia Cristopher Lopez 1374')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado') 
plt.show()
